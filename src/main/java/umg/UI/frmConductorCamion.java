    private void btnBuscarPorIdActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarPorIdActionPerformed
        // TODO add your handling code here:
        if (txtId.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Ingresa un ID para realizar la búsqueda.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            int idBuscado = Integer.parseInt(txtId.getText().trim());
            ConductorCamionDAO dao = new ConductorCamionDAO();
            ConductorCamion cc = dao.buscarPorId(idBuscado);

            if (cc != null) {
                txtFecha.setText(cc.getFecha() != null ? cc.getFecha() : "");

                if (cc.getConductor() != null) {
                    for (int i = 0; i < cbConductor.getItemCount(); i++) {
                        Camionero item = cbConductor.getItemAt(i);
                        if (item != null && item.getIdCamionero() == cc.getConductor().getIdCamionero()) {
                            cbConductor.setSelectedIndex(i);
                            break;
                        }
                    }
                }

                if (cc.getCamion() != null) {
                    for (int i = 0; i < cbCamion.getItemCount(); i++) {
                        Camion item = cbCamion.getItemAt(i);
                        if (item != null && item.getIdCamion() == cc.getCamion().getIdCamion()) {
                            cbCamion.setSelectedIndex(i);
                            break;
                        }
                    }
                }
            } else {
                JOptionPane.showMessageDialog(this, "No se encontró ningún registro con ese ID.", "Sin resultados", JOptionPane.INFORMATION_MESSAGE);
            }

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID debe ser un número entero válido.", "Error de formato", JOptionPane.ERROR_MESSAGE);
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, "Error en la Base de Datos: " + exp.getMessage(), "Error SQL", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnBuscarPorIdActionPerformed

