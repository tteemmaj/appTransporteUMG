    private void btnInsertarActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnInsertarActionPerformed
        // TODO add your handling code here:
        if (txtId.getText().trim().isEmpty()) {
            JOptionPane.showMessageDialog(this, "Por favor ingrese el ID de la asignación.", "Advertencia", JOptionPane.WARNING_MESSAGE);
            return;
        }

        try {
            Camionero conductorSel = (Camionero) cbConductor.getSelectedItem();
            Camion camionSel = (Camion) cbCamion.getSelectedItem();

            ConductorCamion cc = new ConductorCamion();
            cc.setIdConductorCamion(Integer.parseInt(txtId.getText().trim()));
            cc.setConductor(conductorSel);
            cc.setCamion(camionSel);
            cc.setFecha(txtFecha.getText().trim());

            ConductorCamionDAO dao = new ConductorCamionDAO();
            dao.insertar(cc);

            cargarConductorCamion();
            limpiarCampos();
            JOptionPane.showMessageDialog(this, "Asignación registrada correctamente.");

        } catch (NumberFormatException e) {
            JOptionPane.showMessageDialog(this, "El ID debe ser un número entero válido.", "Error de formato", JOptionPane.ERROR_MESSAGE);
        } catch (SQLException exp) {
            JOptionPane.showMessageDialog(this, "Error en la Base de Datos: " + exp.getMessage(), "Error SQL", JOptionPane.ERROR_MESSAGE);
        }
    }//GEN-LAST:event_btnInsertarActionPerformed

