    public void cargarDesplegables() {
        try {
            CamioneroDAO camioneroDAO = new CamioneroDAO();
            List<Camionero> listaCamioneros = camioneroDAO.obtenerTodos();
            cbConductor.removeAllItems();
            for (Camionero c : listaCamioneros) {
                cbConductor.addItem(c);
            }

            cbConductor.setRenderer(new DefaultListCellRenderer() {
                @Override
                public java.awt.Component getListCellRendererComponent(javax.swing.JList<?> list, Object value, int index, boolean isSelected, boolean cellHasFocus) {
                    super.getListCellRendererComponent(list, value, index, isSelected, cellHasFocus);
                    if (value instanceof Camionero) {
                        Camionero c = (Camionero) value;
                        setText(c.getIdCamionero() + " - " + c.getNombre() + " " + c.getApellido());
                    }
                    return this;
                }
            });

            CamionDAO camionDAO = new CamionDAO();
            List<Camion> listaCamiones = camionDAO.obtenerTodos();
            cbCamion.removeAllItems();
            for (Camion cam : listaCamiones) {
                cbCamion.addItem(cam);
            }

            cbCamion.setRenderer(new DefaultListCellRenderer() {
                @Override
                public java.awt.Component getListCellRendererComponent(javax.swing.JList<?> list, Object value, int index, boolean isSelected, boolean cellHasFocus) {
                    super.getListCellRendererComponent(list, value, index, isSelected, cellHasFocus);
                    if (value instanceof Camion) {
                        Camion cam = (Camion) value;
                        setText(cam.getIdCamion() + " - " + cam.getModelo() + " (" + cam.getNoPlaca() + ")");
                    }
                    return this;
                }
            });

        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al cargar listas desplegables: " + e.getMessage(), "Error SQL", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void cargarConductorCamion() {
        DefaultTableModel modelo = (DefaultTableModel) tblConductorCamion.getModel();
        modelo.setRowCount(0);

        ConductorCamionDAO dao = new ConductorCamionDAO();
        try {
            List<ConductorCamion> lista = dao.obtenerTodos();
            for (ConductorCamion cc : lista) {
                String nombreConductor = (cc.getConductor() != null) 
                        ? cc.getConductor().getIdCamionero() + " - " + cc.getConductor().getNombre() + " " + cc.getConductor().getApellido()
                        : "Sin asignar";

                String datosCamion = (cc.getCamion() != null)
                        ? cc.getCamion().getIdCamion() + " - " + cc.getCamion().getModelo()
                        : "Sin asignar";

                modelo.addRow(new Object[]{
                    cc.getIdConductorCamion(),
                    nombreConductor,
                    datosCamion,
                    cc.getFecha()
                });
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al cargar la lista: " + e.getMessage(), "Error SQL", JOptionPane.ERROR_MESSAGE);
        }
    }

    private void limpiarCampos() {
        txtId.setText("");
        txtFecha.setText("");
        if (cbConductor.getItemCount() > 0) {
            cbConductor.setSelectedIndex(0);
        }
        if (cbCamion.getItemCount() > 0) {
            cbCamion.setSelectedIndex(0);
        }
        txtId.requestFocus();
    }

