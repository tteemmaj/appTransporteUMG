    private void cargarCamioneros() {
        DefaultTableModel modelo = (DefaultTableModel) tblCamionero.getModel();
        modelo.setRowCount(0); // Limpiar filas

        CamioneroDAO dao = new CamioneroDAO();
        try {
            List<Camionero> lista = dao.obtenerTodos();
            for (Camionero c : lista) {
                modelo.addRow(new Object[]{
                    c.getIdCamionero(),
                    c.getNombre(),
                    c.getApellido(),
                    c.getDireccion(),
                    c.getSalario(),
                    c.getPoblacion(),
                    c.getDpi(),
                    c.getTelefono()
                });
            }
        } catch (SQLException e) {
            JOptionPane.showMessageDialog(this, "Error al cargar camioneros: " + e.getMessage());
        }
    }
    
