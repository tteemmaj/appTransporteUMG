    private void btnBuscarPorIdActionPerformed(java.awt.event.ActionEvent evt) {//GEN-FIRST:event_btnBuscarPorIdActionPerformed
        // TODO add your handling code here:
        if (txtId.getText().trim().isEmpty()) {
        JOptionPane.showMessageDialog(this, "Ingresa un ID para buscar.", "Advertencia", JOptionPane.WARNING_MESSAGE);
        return;
    }

    try {
        int idBuscado = Integer.parseInt(txtId.getText().trim());
        CamionDAO dao = new CamionDAO();
        Camion c = dao.buscarPorId(idBuscado);

        if (c != null) {
            txtModelo.setText(c.getModelo() != null ? c.getModelo() : "");
            txtTipo.setText(c.getTipo() != null ? c.getTipo() : "");
            txtPotencia.setText(c.getPotencia() != null ? String.valueOf(c.getPotencia()) : "");
            txtPlaca.setText(c.getNoPlaca() != null ? c.getNoPlaca() : "");
        } else {
            JOptionPane.showMessageDialog(this, "No se encontró ningún camión con ese ID.", "Sin resultados", JOptionPane.INFORMATION_MESSAGE);
        }

    } catch (NumberFormatException e) {
        JOptionPane.showMessageDialog(this, "El ID debe ser un número entero.", "Error de formato", JOptionPane.ERROR_MESSAGE);
    } catch (SQLException exp) {
        JOptionPane.showMessageDialog(this, "Error en la Base de Datos: " + exp.getMessage(), "Error SQL", JOptionPane.ERROR_MESSAGE);
    }
    }//GEN-LAST:event_btnBuscarPorIdActionPerformed

