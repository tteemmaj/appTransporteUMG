    private void cargarCamiones() {
    javax.swing.table.DefaultTableModel modelo = (javax.swing.table.DefaultTableModel) tblCamion.getModel();
    modelo.setRowCount(0);

    CamionDAO dao = new CamionDAO();
    try {
        List<Camion> lista = dao.obtenerTodos();
        for (Camion c : lista) {
            modelo.addRow(new Object[]{
                c.getIdCamion(),
                c.getModelo(),
                c.getTipo(),
                c.getPotencia(),
                c.getNoPlaca()
            });
        }
    } catch (SQLException e) {
        JOptionPane.showMessageDialog(this, "Error al cargar camiones: " + e.getMessage());
    }
}
